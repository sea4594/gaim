"""Paired synthetic hidden-world tests; measure information value, not fun.

Worlds share exactly the same currently visible board and public card sizes.
Only unseen offer contents differ. The independent worlds are NOT claimed to
be generated by the current shipping procedural deck.
"""
from __future__ import annotations
import argparse,json,random
from collections import Counter
from experiments.phase15_forecast_council import (
    information_value,make_world,payoff_table,resolve,candidate_edits,private_view,public_view,truthful_signal,signal_value,two_signal_value)
from experiments.phase06_lab import Experiment,step


def wave(rng,n):
    return tuple((rng.randrange(3),rng.choice((-1,1)),rng.choice((1,1,2))) for _ in range(n))


def base_board(seed):
    g=Experiment.new('market',seed=seed)
    # Only information already visible after two normal storms belongs to board.
    for _ in range(2): g=step(g,draft=0)
    if g.state.over:raise AssertionError('invalid reached-board sample')
    return g


def survey(n=80,start=210000,worlds=4,horizon=2,metric="heuristic"):
    if worlds<2 or worlds>6:raise ValueError('expected 2..6 comparable hidden worlds')
    rng=random.Random(start); counts=Counter(); best=None
    for seed in range(start,start+n):
        g=base_board(seed)
        variants=[]
        # Every alternative future has the same *public* offered counts.
        for k in range(worlds):
            a=wave(rng,2)
            b=wave(rng,2)
            variants.append(make_world(g,a,b))
        assert len({public_view(v) for v in variants})==1
        if len({private_view(v,'routes') for v in variants})==1:
            counts['same_route_sensors']+=1
        tables=[payoff_table(v,horizon=horizon,metric=metric) for v in variants]
        info=information_value(tables)
        counts['boards']+=1
        counts['action_opportunities']+=info['edits']
        if info['perfect_value']>1e-7:counts['perfect_information_useful']+=1
        if info['signal_value']>1e-7:counts['one_bit_upper_useful']+=1
        if info['signal_value']>1e-7 and (best is None or info['signal_value']>best['info']['signal_value']):
            best={'seed':seed,'info':info,
                  'public':repr(public_view(variants[0])),
                  'worlds':[{'offers':[v.game.deck[i] for i in v.game.available],
                             'routes':private_view(v,'routes').values,
                             'polarity':private_view(v,'polarity').values,
                             'strength':private_view(v,'strength').values,
                             'best_action':max(tables[ix],key=lambda a:max(tables[ix][a])),
                             'payoffs':{str(a):list(row) for a,row in tables[ix].items()}}
                            for ix,v in enumerate(variants)]}
        for kind in ('left_route','negative','large'):
            bits=[truthful_signal(v,kind) for v in variants]
            gain=signal_value(tables,bits)-info['blind']
            counts['sum_truthful_'+kind]+=gain
            counts['truthful_'+kind+'_useful']+=gain>1e-7
        pair=('left_route','negative')
        bits_a=[truthful_signal(v,pair[0]) for v in variants]
        bits_b=[truthful_signal(v,pair[1]) for v in variants]
        v_both=two_signal_value(tables,bits_a,bits_b)
        v_a=signal_value(tables,bits_a)
        v_b=signal_value(tables,bits_b)
        counts['sum_two_signal_gain']+=v_both-info['blind']
        counts['sum_complementarity']+=v_both-max(v_a,v_b)
        counts['two_signal_useful']+=(v_both-info['blind'])>1e-7
        counts['strict_two_sensor_synergy']+=v_both>max(v_a,v_b)+1e-7
        for k in ('blind','one_bit_upper','perfect_upper','signal_value','perfect_value'):
            counts['sum_'+k]+=info[k]
    out={k:(round(v,4) if k.startswith('sum_') else v) for k,v in counts.items()}
    return {'method':'Four possible hidden storm worlds per identical reached board; optimal edit commitment, best scout draft response, optimistic optimal 1-bit signaling upper bound. Next-state heuristic only.',
            'cases':n,'horizon':horizon,'metric':metric,'hidden_worlds_per_board':worlds,'counts':out,
            'mean_signal_value':round(counts['sum_signal_value']/n,4),
            'mean_truthful_gain':{k:round(counts['sum_truthful_'+k]/n,4) for k in ('left_route','negative','large')},
            'mean_perfect_information_value':round(counts['sum_perfect_value']/n,4),
            'mean_two_signal_gain':round(counts['sum_two_signal_gain']/n,4),
            'mean_two_sensor_complementarity':round(counts['sum_complementarity']/n,4),
            'example':best,
            'limitations':['Synthetic hidden storm cards sampled independently of the current storm generator.',
                           'A one-bit partition chosen with full data is an ORACLE bound, not a playable signal rule.',
                           'Truthful signal benchmarks still use an oracle receiver trained on all synthetic worlds.',
                           'Score is a tactical heuristic rather than a multi-round win probability.',
                           'Full voice chat can circumvent structured information sharing.',
                           'One operator edit, not a complete four-player game.']}

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--cases',type=int,default=80);p.add_argument('--start',type=int,default=210000);p.add_argument('--horizon',type=int,default=2);p.add_argument('--metric',choices=('heuristic','survival'),default='heuristic')
    args=p.parse_args()
    print(json.dumps(survey(args.cases,args.start,horizon=args.horizon,metric=args.metric),indent=2,default=str))
